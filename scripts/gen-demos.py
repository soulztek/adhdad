# Builds looping 2-frame animated WebP demos from yuhonas/free-exercise-db (Unlicense / public domain).
# Run from the project root with a checkout of the repo at FEDB. Images reused from the Golf Speed Plan app are listed in REUSE.
import json, os
from PIL import Image
FEDB = os.environ.get("FEDB", "/workspace/fedb")
D = {
 # key: (free-exercise-db id, [cues], note)
 "goblet": ("Goblet_Squat", ["Hold the bell at your chest, elbows down", "Sit between the hips, chest tall", "Only as deep as your knees and back are happy"], None),
 "kbdl": ("Stiff-Legged_Dumbbell_Deadlift", ["Bell between the feet, push the hips back", "Flat back, soft knees, stand up tall", "Grip the floor; no rounding"], "Shown with two dumbbells; same hinge holding one kettlebell between the feet"),
 "swing": ("One-Arm_Kettlebell_Swings", ["Light bell, two hands, hinge not squat", "Snap the hips; arms just guide it to chest height", "Stop the set when the hinge gets sloppy"], "Shown one-handed; do it two-handed with a light bell"),
 "press": ("Dumbbell_Floor_Press", ["Lie on the floor, elbows about 45 degrees", "Lower until upper arms touch the floor", "Press up; the floor protects your shoulders"], None),
 "row": ("One-Arm_Dumbbell_Row", ["Hand and knee on a bench or couch, flat back", "Pull the bell to your hip pocket", "Lower slowly, no twisting"], None),
 "ohp": ("Seated_Dumbbell_Press", ["Sit tall, ribs down, core braced", "Press up without arching the low back", "Seated is fine and often kinder to the back"], None),
 "lunge": ("Dumbbell_Rear_Lunge", ["Step back, lower the back knee gently", "Front knee tracks over the toes", "Bodyweight first; hold a wall if needed"], None),
 "farmer": ("Farmers_Walk", ["Bells at your sides, stand tall", "Short steps, shoulders down and back", "Walk 30-40 s, set down with a flat back"], "Shown with heavy handles; use two dumbbells or kettlebells"),
 "suitcase": ("Farmers_Walk", ["One bell in ONE hand only", "Don't lean; stay perfectly upright", "Switch hands halfway"], "Shown with two weights; carry just one on one side"),
 "bridge": ("Butt_Lift_Bridge", ["Feet flat, push through the heels", "Squeeze the glutes at the top, ribs down", "Lower slowly"], None),
 "deadbug": ("Dead_Bug", ["Low back gently pressed into the floor", "Reach opposite arm and leg slowly", "Exhale as you reach"], None),
 "plank": ("Plank", ["Elbows under shoulders, body in one line", "Squeeze glutes, breathe", "Knees down is a fine version"], None),
 "birddog": ("Glute_Kickback", ["On all fours, back flat like a table", "Reach one leg back AND the opposite arm forward", "Slow, no wobble; switch sides"], "Closest match: same all-fours start; add the opposite-arm reach"),
 "squat": ("Bodyweight_Squat", ["Sit back like into a chair", "Chest tall, heels down", "Easy pace, pain-free depth"], None),
 "arms": ("Arm_Circles", ["Small circles, then bigger", "Forward 15 s, backward 15 s", "Relax the neck"], None),
 "catcow": ("Cat_Stretch", ["On all fours, round the back up", "Then let the belly drop gently", "Move with your breath"], None),
 "incpush": ("Incline_Push-Up", ["Hands on a counter or couch", "Body in one line, chest to the edge", "Higher hands = easier"], None),
}
REUSE = {
 "wgs": ("img/worlds-greatest-stretch.webp", "World's Greatest Stretch", ["Big lunge, elbow drops inside the front foot", "Rotate and reach to the ceiling", "Back knee can rest down"], None),
 "child": ("img/childs-pose.webp", "Child's Pose", ["Sit back toward the heels", "Arms long, breathe into the back", "30-60 s"], None),
 "hipflex": ("img/kneeling-hip-flexor.webp", "Kneeling Hip Flexor", ["Tuck the pelvis under", "Squeeze the back-leg glute", "Great after sitting all day"], None),
}
os.makedirs("public/img", exist_ok=True)
made = {}
for key, (fid, cues, note) in D.items():
    if fid in made: continue
    frames = []
    for j in range(2):
        im = Image.open(f"{FEDB}/exercises/{fid}/{j}.jpg").convert("RGB")
        w = 320; h = round(im.height * w / im.width)
        frames.append(im.resize((w, h), Image.LANCZOS))
    slug = fid.lower().replace("_", "-")
    frames[0].save(f"public/img/{slug}.webp", save_all=True, append_images=frames[1:], duration=900, loop=0, quality=62, method=6)
    name = json.load(open(f"{FEDB}/exercises/{fid}.json"))["name"]
    made[fid] = {"file": f"img/{slug}.webp", "w": frames[0].width, "h": frames[0].height, "name": name}
demos = {}
for key, (fid, cues, note) in D.items():
    m = made[fid]
    demos[key] = {"img": m["file"], "w": m["w"], "h": m["h"], "src": m["name"], "cues": cues, "note": note}
for key, (f, name, cues, note) in REUSE.items():
    im = Image.open("public/" + f)
    demos[key] = {"img": f, "w": im.width, "h": im.height, "src": name, "cues": cues, "note": note}
used = sorted(set([m["name"] for m in made.values()] + [r[1] for r in REUSE.values()]))
open("src/demos.generated.ts", "w").write("// generated by scripts/gen-demos.py\nexport const DEMOS: Record<string, any> = " + json.dumps(demos, indent=1, ensure_ascii=False) + ";\nexport const FEDB_USED: string[] = " + json.dumps(used) + ";\n")
tot = sum(os.path.getsize("public/" + d["img"]) for d in demos.values())
print(len(made), "new images,", len(demos), "demo keys")
